"""Generate apworld data.py from the game's own level order (runtime dump) and decompiled level files.

usage: gen_data.py <ap_dump.txt> <decompiled levels dir> <out data.py>
"""
import re, sys, os

# (folder, display name) in the game's own mission order
EPISODES = [
    ("theme1", "Pig Bang"), ("theme2", "Cold Cuts"), ("theme3", "Fry Me to the Moon"),
    ("theme4", "Utopia"), ("theme5", "Red Planet"), ("theme6", "Pig Dipper"),
    ("theme7", "Cosmic Crystals"), ("theme81", "Beak Impact 1"), ("theme82", "Beak Impact 2"),
    ("theme9", "Brass Hogs"), ("dangerZone", "Danger Zone"), ("bonus", "Eggsteroids"),
]
BIRDS = ["RedBird", "SmallBlueBird", "LaserBird", "BlackBird", "IceBird", "RedBigBird", "GlobeBird"]
BOSSES = {"LevelBossTheme1", "LevelBossTheme2", "LevelT2B_10", "LevelBossTheme4", "T5_Boss", "T6_Boss", "T7_Boss",
          "level_Miner20"}


def main(dump, levels_dir, out):
    t = open(dump).read()
    ml = t[t.index("myLevels = {"):t.index("\nepisodes = {")]
    levels = {m.group(1): re.findall(r'"([^"]+)"', m.group(2))
              for m in re.finditer(r"\n    (\w+) = \{\n        ([^\n]*)", ml)}
    lt = t[t.index("levelTypes = {"):]
    types = dict(re.findall(r'(\w+) = "([^"]*)"', lt))

    lines = ["# Generated by ap_mod/tools/gen_data.py from the game's data. Do not edit by hand.",
             "# EPISODES: (folder, name, [(level file, index in myLevels, number shown in game, birds, is_boss)])",
             "EPISODES = ["]
    for folder, name in EPISODES:
        rows, n = [], 0
        for idx, lvl in enumerate(levels[folder], start=1):
            if types.get(lvl) in ("comic", "menu"):
                continue
            n += 1
            src = open(os.path.join(levels_dir, folder, lvl + ".lua"), encoding="latin1").read()
            # bird types appear as exact string literals (definition = "X" or via a temp variable)
            lits = set(re.findall(r'"([A-Za-z]+)"', src))
            birds = tuple(b for b in BIRDS if b in lits)
            assert birds, f"{folder}/{lvl} has no birds"
            rows.append((lvl, idx, n, birds, lvl in BOSSES))
        lines.append(f"    ({folder!r}, {name!r}, [")
        lines += [f"        {r!r}," for r in rows]
        lines.append("    ]),")
    lines.append("]")
    open(out, "w").write("\n".join(lines) + "\n")
    found = {r for f, _ in EPISODES for r in levels[f]} & BOSSES
    assert found == BOSSES, BOSSES - found


if __name__ == "__main__":
    main(*sys.argv[1:4])
